/**
 * A sticker: the mark on its own tile, in its own colours, a little askew,
 * `size` px across, centred on (cx, cy).
 */
export function drawSticker(ctx: CanvasRenderingContext2D, name: LogoName, cx: number, cy: number, size: number, tilt: number): void {
  const brand = BRANDS[name];
  ctx.save();
  ctx.translate(cx, cy);
  ctx.rotate(tilt);
  const h = size / 2;
  ctx.beginPath();
  ctx.roundRect(-h, -h, size, size, size * 0.24);
  if (typeof brand.tile === 'string') ctx.fillStyle = brand.tile;
  else {
    const g = ctx.createLinearGradient(-h, h, h, -h);
    brand.tile.forEach((c, k) => g.addColorStop(k / (brand.tile.length - 1), c));
    ctx.fillStyle = g;
  }
  ctx.shadowColor = 'rgba(40, 37, 31, 0.22)';
  ctx.shadowBlur = size * 0.12;
  ctx.shadowOffsetY = size * 0.04;
  ctx.fill();
  ctx.restore();
  ctx.save();
  ctx.translate(cx, cy);
  ctx.rotate(tilt);
  const mark = size * (name === 'linkedin' ? 0.86 : 0.6);
  if (brand.glitch) {
    const d = Math.max(0.5, size * 0.035);
    drawLogo(ctx, name, -d, -d, mark, brand.glitch[0]);
    drawLogo(ctx, name, d, d, mark, brand.glitch[1]);
  }
  if (name === 'linkedin') {
    // its mark is a tile with the letters cut out: on a tile of its own blue, only the letters, in white
    lettersPath ??= new Path2D(LINKEDIN_LETTERS);
    ctx.save();
    ctx.translate(-mark / 2, -mark / 2);
    ctx.scale(mark / 24, mark / 24);
    ctx.fillStyle = brand.mark;
    ctx.fill(lettersPath);
    ctx.restore();
  } else drawLogo(ctx, name, 0, 0, mark, brand.mark);
  ctx.restore();
}

