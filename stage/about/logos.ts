export type LogoName = keyof typeof LOGOS;

export const isLogo = (s: string | undefined): s is LogoName => !!s && s in LOGOS;

const cache = new Map<LogoName, Path2D>();

function pathOf(name: LogoName): Path2D {
  let p = cache.get(name);
  if (!p) cache.set(name, (p = new Path2D(LOGOS[name])));
  return p;
}

/** The mark alone, `size` px across, centred on (cx, cy). */
export function drawLogo(ctx: CanvasRenderingContext2D, name: LogoName, cx: number, cy: number, size: number, colour: string): void {
  ctx.save();
  ctx.translate(cx - size / 2, cy - size / 2);
  ctx.scale(size / 24, size / 24);
  ctx.fillStyle = colour;
  ctx.fill(pathOf(name));
  ctx.restore();
}

/**
 * Each mark's own colours, as its owners show it (their app icons): the tile,
 * the mark on it, and for TikTok the cyan and red it casts either side.
 * Instagram's tile is its gradient, yellow at the bottom-left to purple at the top-right.
 */
interface Brand {
  readonly tile: string | readonly string[];
  readonly mark: string;
  readonly glitch?: readonly [string, string];
}

